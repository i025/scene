def write_json(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def delivered_image_metadata(path):
    """Measure the original deliverable, never an evaluator rerender or an upscale."""
    path = Path(path)
    result = {'authored_filename': 'final.png', 'exists': path.is_file(),
              'file_size_bytes': None, 'png_magic_valid': None, 'format': None,
              'width': None, 'height': None, 'mode': None, 'full_decode_success': False,
              'readable': None, 'validation_status': 'missing', 'error': None,
              'provenance': 'Original H-delivered file; not the evaluator author-camera rerender',
              'content_changes': 'none; no resizing, upsampling, conversion or repair'}
    if not result['exists']:
        return result
    try:
        result['file_size_bytes'] = path.stat().st_size
        with path.open('rb') as stream:
            # PNG's standard format signature is a file-format check, not a
            # checksum, content fingerprint, or identity verification scheme.
            result['png_magic_valid'] = stream.read(8) == b'\x89PNG\r\n\x1a\n'
        result['readable'] = True
    except OSError as error:
        result.update(validation_status='evaluator_file_read_error', readable=False,
                      error=str(error).replace(str(path), 'delivered_final.png'))
        return result
    try:
        with Image.open(path) as picture:
            result.update(format=picture.format, width=picture.width, height=picture.height, mode=picture.mode)
            picture.load()
            result.update(full_decode_success=True, validation_status='decoded')
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError) as error:
        result.update(validation_status='invalid_image',
                      error=str(error).replace(str(path), 'delivered_final.png'))
    return result


def enrich_delivered_evidence(evidence_folder):
    """Add missing delivery facts to saved evidence, retaining the original JSON once.

    This helper performs no Blender/model call and never changes scores or the
    generator artifact. Existing evaluations must be preserved by the caller
    before a fresh judgement under the documented evaluator amendment.
    """
    folder = Path(evidence_folder).resolve()
    status_path, facts_path = folder / 'evidence_status.json', folder / 'scene_facts.json'
    status, facts = json.loads(status_path.read_text()), json.loads(facts_path.read_text())
    source = Path(status['source']).parent / 'final.png'
    metadata = delivered_image_metadata(source)
    delivered_images = []
    if metadata['exists'] and metadata['readable']:
        snapshot = folder / 'delivered_final.png'
        if not snapshot.exists():
            shutil.copy2(source, snapshot)
        elif snapshot.stat().st_size != metadata['file_size_bytes']:
            raise ValueError('Saved delivered artifact byte size changed; preserve the prior evidence and inspect the source')
        metadata['snapshot_filename'] = snapshot.name
        if metadata['full_decode_success'] and metadata['format'] in {'PNG', 'JPEG', 'WEBP'}:
            suffix = {'PNG': '.png', 'JPEG': '.jpg', 'WEBP': '.webp'}[metadata['format']]
            attachment = folder / ('delivered_final' + suffix)
            if not attachment.exists():
                shutil.copy2(source, attachment)
            delivered_images.append(attachment.name)
    previous = folder / 'scene_facts_before_delivered_evidence.json'
    if not previous.exists():
        shutil.copy2(facts_path, previous)
    facts['delivered_artifacts'] = [metadata]
    facts['delivery_evidence_version'] = 'original_delivery_metadata_A02'
    write_json(facts_path, facts)
    write_json(folder / 'delivered_artifact_provenance.json', {
        'source_file': str(source), 'source_rule': 'Exact original blend.parent/final.png; no path search',
        'evidence_version': 'original_delivery_metadata_A02', 'measured_at': time.time(),
        'original_artifact_untouched': True, 'original_scene_facts_backup': previous.name,
        'attached_images': delivered_images, 'metadata': metadata,
    })
    status.update(delivered_images=delivered_images, delivery_evidence_version='original_delivery_metadata_A02')
    write_json(status_path, status)
    return status


def score_bw(rubrics, rubric_scores, dimension_scores):
    """Validate exact coverage before applying the uncapped official 1:1 formula."""
    expected = {r['id'] for r in rubrics}
    ids = [r['id'] for r in rubric_scores]
    dimensions = [r['id'] for r in dimension_scores]
    if not rubrics or set(ids) != expected or len(ids) != len(expected):
        raise ValueError('Rubric coverage missing or duplicated')
    if set(dimensions) != {d[0] for d in DIMENSIONS} or len(dimensions) != 8:
        raise ValueError('Eight-dimension coverage missing or duplicated')
    if any(type(r['score']) is not int or r['score'] not in (0, 1) for r in rubric_scores):
        raise ValueError('Rubric scores must be measured binary integers')
    if any(type(r['score']) is not int or not 1 <= r['score'] <= 10 for r in dimension_scores):
        raise ValueError('Eight dimensions must be measured integer ratings 1..10')
    by_id = {r['id']: r['score'] for r in rubric_scores}
    total_weight = sum(r['importance_weight'] for r in rubrics)
    if total_weight <= 0 or any(r['importance_weight'] <= 0 for r in rubrics):
        raise ValueError('Rubric weights must be positive')
    rubric = 100 * sum(r['importance_weight'] * by_id[r['id']] for r in rubrics) / total_weight
    dimension = 10 * sum(r['score'] for r in dimension_scores) / 8
    return {'S_rubric': rubric, 'S_dimension': dimension, 'S_BW': .5 * (rubric + dimension)}


def qualification(execution_status, evaluation_status, functional_checks):
    """Absolute eligibility; H_start failure never weakens a candidate requirement."""
    checks = [{**check, 'gate_pass': (check['applicable'] and check['measured_pass'] is True)
               if check['required'] else True} for check in functional_checks]
    return {'eligible': execution_status == 'completed' and evaluation_status == 'completed'
                        and all(c['gate_pass'] for c in checks), 'functional_checks': checks}


def summarize(records, scheduled):
    """Pending/evaluator failure stays null; algorithm failure has separate zero utility."""
    evaluated = [r for r in records if r['evaluation_status'] == 'completed']
    finished = [r for r in records if r['execution_status'] in {'completed', 'failed', 'timeout', 'invalid'}]
    execution_success = sum(r['execution_status'] == 'completed' for r in finished)
    generated_failures = [r for r in records if r['execution_status'] in {'failed', 'timeout', 'invalid'}]
    known_utility = [r['S_BW'] for r in evaluated] + [0.0] * len(generated_failures)
    return {'all_scheduled': scheduled, 'execution_finished': len(finished),
            'execution_succeeded': execution_success,
            'execution_success_rate_all_scheduled': execution_success / scheduled if finished and scheduled else None,
            'evaluation_completed': len(evaluated),
            'evaluation_coverage': len(evaluated) / scheduled if scheduled else None,
            'conditional_BW_mean': sum(r['S_BW'] for r in evaluated) / len(evaluated) if evaluated else None,
            'end_to_end_utility': sum(known_utility) / scheduled
                                 if len(known_utility) == scheduled and scheduled else None,
            'end_to_end_utility_known_count': len(known_utility),
            'pending': scheduled - len(finished),
            'evaluation_failed': sum(r['evaluation_status'] == 'eval_failed' for r in records)}


def collect_evidence(blend, folder, cfg, *, preview=False, interior=True):
    """One bounded process per render: preserve per-frame timeout and tree resources."""
    folder = Path(folder).resolve()
    folder.mkdir(parents=True, exist_ok=False)
    blend = Path(blend).resolve()
    frozen = folder / 'artifact.blend'
    shutil.copy2(blend, frozen)
    settings = {'preview': preview, 'interior': interior,
                'resolution': cfg['evaluation']['preview_width'] if preview else cfg['evaluation']['width'],
                'samples': cfg['evaluation']['preview_samples'] if preview else cfg['evaluation']['samples'],
                'threads': cfg['resources']['threads_per_blender'], 'seed': cfg['render']['seed'],
                'device': 'CPU', 'dependency_source_folder': str(blend.parent)}
    write_json(folder / 'settings.json', settings)
    write_json(folder / 'upstream.json', UPSTREAM)
    result = {'label': LABEL, 'preview': preview, 'execution_status': 'running',
              'evaluation_status': 'not_started', 'S_rubric': None, 'S_dimension': None, 'S_BW': None,
              'started': time.time(), 'images': [], 'source': str(blend),
              'device': 'CPU', 'threads': settings['threads'], 'renders_attempted': 0,
              'renders_completed': 0, 'failure_type': None}
    write_json(folder / 'evidence_status.json', result)
    base = [cfg['blender']['executable'], '--background', '--threads', str(settings['threads']),
            '--python-exit-code', '2', '--python', str(ROOT / 'eval_blend.py'), '--',
            '--blend', str(frozen), '--folder', str(folder), '--settings', str(folder / 'settings.json')]
    environment = cpu_environment(threads=settings['threads'], cuda_visible='')
    memory_limit = int(cfg['resources']['memory_limit_gb'] * 1024 ** 3)
    stages = [('inspect', base, cfg['blender']['build_timeout'])]
    for name, command, timeout in stages:
        with (folder / f'{name}.log').open('w') as log:
            measurement = run_measured(command, timeout=timeout,
                                      measurement_path=folder / f'{name}_timing.json',
                                      memory_limit_bytes=memory_limit,
                                      stdout=log, stderr=subprocess.STDOUT, env=environment)
        if measurement['returncode'] != 0 or measurement['timed_out']:
            result.update(execution_status='unknown', evaluation_status='eval_failed',
                          failure_type='scene_inspection_timeout' if measurement['timed_out'] else 'scene_inspection_error',
                          finished=time.time())
            write_json(folder / 'evidence_status.json', result)
            return result
    facts = json.loads((folder / 'scene_facts.json').read_text())
    if not facts['required_dependencies_available'] or facts['camera'] is None:
        result.update(execution_status='invalid', failure_type='missing_dependency_or_author_camera', finished=time.time())
        write_json(folder / 'evidence_status.json', result)
        return enrich_delivered_evidence(folder)
    plan = json.loads((folder / 'view_plan.json').read_text())
    for view in plan['views']:
        name = view['view_id']
        result['renders_attempted'] += 1
        write_json(folder / 'evidence_status.json', result)
        with (folder / f'{name}.log').open('w') as log:
            measurement = run_measured(base + ['--view-id', name], timeout=cfg['blender']['render_timeout'],
                                      measurement_path=folder / f'{name}_timing.json',
                                      memory_limit_bytes=memory_limit,
                                      stdout=log, stderr=subprocess.STDOUT, env=environment)
        if measurement['returncode'] != 0 or measurement['timed_out']:
            result.update(execution_status='completed', evaluation_status='eval_failed',
                          failure_type='render_timeout' if measurement['timed_out'] else 'evaluator_render_error')
            break
        with Image.open(folder / view['file']) as image:
            expected_size = tuple(view['resolution']) if view['kind'] == 'author' else (settings['resolution'],) * 2
            if image.size != expected_size:
                raise ValueError('Evaluator render size violates frozen settings')
            image.verify()
        result['renders_completed'] += 1
        result['images'].append(view['file'])
    else:
        result.update(execution_status='completed', evaluation_status='pending_judge')
    result.update(finished=time.time())
    result['seconds'] = result['finished'] - result['started']
    write_json(folder / 'evidence_status.json', result)
    return enrich_delivered_evidence(folder)


def judge_schema(rubric):
    def obj(fields):
        return {'type': 'object', 'properties': fields, 'required': list(fields), 'additionalProperties': False}
    strings = {'type': 'array', 'items': {'type': 'string'}}
    return obj({
        'evaluation_status': {'type': 'string', 'enum': ['completed', 'eval_failed']},
        'evaluation_error': {'type': ['string', 'null']},
        'rubric_scores': {'type': 'array', 'items': obj({
            'id': {'type': 'string', 'enum': [r['id'] for r in rubric['rubrics']]},
            'score': {'type': ['integer', 'null'], 'minimum': 0, 'maximum': 1},
            'evidence': {'type': 'string'}, 'source_evidence': strings,
            'evidence_route': {'type': 'string', 'enum': ['scene_summary', 'render', 'either']}})},
        'dimension_scores': {'type': 'array', 'items': obj({
            'id': {'type': 'string', 'enum': [d[0] for d in DIMENSIONS]},
            'score': {'type': ['integer', 'null'], 'minimum': 1, 'maximum': 10},
            'evidence': {'type': 'string'}, 'source_evidence': strings})},
    })


def judge_prompt(rubric, facts, views):
    return '''You are the independent anonymous BW-style / CLI-adapted evaluator.
Judge one frozen artifact. You have no research conversation or method/version identity.
Do not run tools, browse files, repair an artifact, infer an unstated hidden answer,
or use reference-image content as evidence that the artifact contains it.
Attached image 0 is the target reference. Subsequent images are author and evaluator
renders, listed in exact attachment order below. Author and evaluator images have
different provenance: defects of an evaluator framing view do not establish defects
of the authored final view. Use all views together. One visible clear view suffices
for presence; reference imagery alone never does. Reasonable matte/stylized surfaces
are acceptable when consistent with target. Do not impose photographic gloss.
Delivery provenance: author.png is an EVALUATOR rerender using the authored camera,
not the originally delivered PNG. delivered_final.png (or its actual-format .jpg/.webp
attachment) is a byte-preserving copy of the ORIGINAL H-delivered final.png. Its
actual Pillow format, PNG signature check, full decoding result and encoded pixel
dimensions are recorded in scene_facts.json:delivered_artifacts. Evaluator renders
cannot satisfy an original-deliverable format or resolution requirement. A measured
delivered size below the frozen rubric requirement, a measured non-PNG payload, an
actually missing final.png, or an invalid/corrupt delivered image is an artifact
requirement failure (score 0 for the corresponding criterion), not missing evaluator
evidence. An evaluator permission/read error is different and remains eval_failed.
Do not infer missing native font/material/configuration facts: if a required fact
was not collected and cannot be established from the supplied evidence, state the
specific missing field rather than guessing. These evidence rules do not alter
rubrics, weights, thresholds, render settings, or the generated artifact.
Scene facts below were read by fixed Blender code from the actual artifact. Names and
declared dependencies are not proof of semantic correctness. Bounds are approximate,
not collision truth; there is no metric scale or hidden-geometry ground truth.
Route each rubric exactly once by its evidence_type: scene_summary MUST use specific
scene_facts.json fields grounded in actual objects/materials/hierarchy; render/either
use visual evidence and name author/evaluator image files. Never replace missing
structural evidence with a visual guess. Each source_evidence must identify actual
scene_facts.json field paths or supplied render filenames. Reference may explain a
target but cannot be the sole positive evidence. Scores are binary 0/1. Clearly
absent/mismatched artifact requirements score 0. If required evaluation evidence is
unavailable or unreadable, output eval_failed, explain, and retain null missing scores.
Score all eight dimensions independently as integer 1..10 using the supplied evidence.
No catastrophic cap or arbitrary weighted recombination is applied. Return only the
provided JSON schema, every rubric ID once and all eight dimension IDs once.
Task and frozen rubric:\n''' + json.dumps(rubric, ensure_ascii=False) + '\nDimensions:\n' + json.dumps(
        [{'id': key, 'definition': text} for key, text in DIMENSIONS], ensure_ascii=False
    ) + '\nAttachment order after reference:\n' + json.dumps(views) + '\nActual scene facts:\n' + json.dumps(facts, ensure_ascii=False)


def validate_evidence_routes(rubric, judged, available_images):
    by_id = {r['id']: r for r in rubric['rubrics']}
    for row in judged['rubric_scores']:
        required_route = by_id[row['id']]['evidence_type']
        if row['evidence_route'] != required_route or not row['evidence'].strip():
            raise ValueError('Rubric evidence route differs from frozen criterion')
        sources = row['source_evidence']
        if required_route == 'scene_summary':
            if not any(s.startswith('scene_facts.json') for s in sources):
                raise ValueError('Structural criterion lacks actual scene-fact evidence')
        elif not any(any(name in source for name in available_images) for source in sources):
            raise ValueError('Visual criterion lacks artifact-render evidence')
    if any(not d['evidence'].strip() or not d['source_evidence'] for d in judged['dimension_scores']):
        raise ValueError('Dimension evidence is incomplete')


def judge_artifact(reference, evidence_folder, rubric, cfg, judge_folder, *, display_order=None):
    evidence_folder = Path(evidence_folder).resolve()
    judge_folder = Path(judge_folder).resolve()
    status = enrich_delivered_evidence(evidence_folder)
    if status['evaluation_status'] != 'pending_judge':
        return status
    facts = json.loads((evidence_folder / 'scene_facts.json').read_text())
    views = list(status['images'] if display_order is None else display_order)
    if sorted(views) != sorted(status['images']):
        raise ValueError('Display-order randomization must preserve every evidence image exactly once')
    views.extend(status['delivered_images'])
    images = [Path(reference).resolve(), *[evidence_folder / p for p in views]]
    prompt = judge_prompt(rubric, facts, views)
    # Transport copies images into a fresh anonymous workspace, disables tools,
    # and records requested/observed model, visible events, usage and failures.
    try:
        text, session = call(prompt, cfg['proposer'], judge_folder, images,
                             role='judge', schema=judge_schema(rubric))
    except RuntimeError as error:
        result = {**status, 'evaluation_status': 'eval_failed', 'failure_type': 'external_judge_failure',
                  'evaluation_error': str(error), 'S_rubric': None, 'S_dimension': None, 'S_BW': None}
        write_json(evidence_folder / 'evaluation.json', result)
        return result
    write_json(judge_folder / 'evaluation_inputs.json', {'reference_attachment_index': 0,
               'artifact_images': views, 'rubric': rubric, 'scene_facts': facts,
               'identity_blinding': 'No method/run/H/M identity in prompt or staged filenames', 'upstream': UPSTREAM})
    try:
        judged = json.loads(text)
        if judged['evaluation_status'] == 'eval_failed':
            result = {**status, **judged, 'S_rubric': None, 'S_dimension': None, 'S_BW': None,
                      'failure_type': 'external_judge_failure'}
        else:
            validate_evidence_routes(rubric, judged, views)
            scores = score_bw(rubric['rubrics'], judged['rubric_scores'], judged['dimension_scores'])
            result = {**status, **judged, **scores, 'failure_type': None}
    except (json.JSONDecodeError, ValueError) as error:
        result = {**status, 'evaluation_status': 'eval_failed', 'failure_type': 'invalid_judge_output',
                  'evaluation_error': str(error), 'S_rubric': None, 'S_dimension': None, 'S_BW': None}
    result['judge_session'] = str(judge_folder)
    result['judge_usage'] = {k: session[k] for k in ['input_tokens', 'output_tokens', 'observed_model', 'seconds']}
    result['same_model_bias_limit'] = 'Research and independent judge use Astra; separate sessions do not establish human independence.'
    write_json(evidence_folder / 'evaluation.json', result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=ROOT / 'config.json')
    parser.add_argument('--blend', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--preview', action='store_true')
    parser.add_argument('--exterior', action='store_true')
    parser.add_argument('--reference', type=Path)
    parser.add_argument('--rubric', type=Path)
    args = parser.parse_args()
    cfg = json.loads(args.config.read_text())
    result = collect_evidence(args.blend, args.output, cfg, preview=args.preview, interior=not args.exterior)
    if args.reference and args.rubric:
        result = judge_artifact(args.reference, args.output, json.loads(args.rubric.read_text()), cfg, args.output / 'judge')
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
